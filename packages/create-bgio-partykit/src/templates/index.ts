/**
 * Bundled template files for the create-bgio-partykit CLI.
 *
 * Template variables use the `{{VARIABLE}}` syntax and are replaced
 * at scaffold time with user-provided values:
 *   - {{PROJECT_NAME}}      — kebab-case project directory name
 *   - {{GAME_NAME}}         — boardgame.io game name (defaults to project name)
 *   - {{GAME_NAME_PASCAL}}  — PascalCase version of game name (for TypeScript identifiers)
 *   - {{NUM_PLAYERS}}       — number of players (default 2)
 *   - {{BGIO_PK_VERSION}}   — bgio-partykit dependency version
 */

export interface TemplateVars {
  projectName: string;
  gameName: string;
  numPlayers: number;
  bgioPkVersion: string;
}

function toPascalCase(kebab: string): string {
  return kebab
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function substitute(template: string, vars: TemplateVars): string {
  const gameNamePascal = toPascalCase(vars.gameName);
  return template
    .replace(/\{\{PROJECT_NAME\}\}/g, vars.projectName)
    .replace(/\{\{GAME_NAME\}\}/g, vars.gameName)
    .replace(/\{\{GAME_NAME_PASCAL\}\}/g, gameNamePascal)
    .replace(/\{\{NUM_PLAYERS\}\}/g, String(vars.numPlayers))
    .replace(/\{\{BGIO_PK_VERSION\}\}/g, vars.bgioPkVersion);
}

export interface TemplateFile {
  path: string;
  content: (vars: TemplateVars) => string;
}

