/**
 * Get all template files with variable substitution applied.
 */
export function getTemplates(_vars: TemplateVars): TemplateFile[] {
  return rawTemplates.map(({ path, content }) => ({
    path,
    content: (v: TemplateVars) => substitute(content, v),
  }));
}
